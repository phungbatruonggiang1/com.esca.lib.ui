// and a font file, or cairo and pango -- would be megabytes of dependency to
// draw the word "person". Each glyph is seven rows of five pixels, one bit
// per pixel, most significant bit on the left.
//
// Only the characters the overlay actually needs are defined: letters, digits
// and a little punctuation. Anything else draws as a blank, which is a
// visible but harmless gap rather than a crash.

