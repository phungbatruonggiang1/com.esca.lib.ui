/// Rows for one character, or nullptr when the font has no glyph for it.
inline const uint8_t *glyph_rows(char c)
{
    // Built once into a direct index: text is redrawn every frame, and a
    // linear scan of the table per character would be work for nothing.
    static const std::array<const uint8_t *, 128> index = [] {
        std::array<const uint8_t *, 128> table{};
        for (const Glyph &g : kGlyphs)
            table[static_cast<unsigned char>(g.c)] = g.rows;
        return table;
    }();

    const auto u = static_cast<unsigned char>(c);
    return u < index.size() ? index[u] : nullptr;
}

